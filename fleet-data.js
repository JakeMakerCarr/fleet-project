export function getCanonicalVehicleName(vehicle) {
  return VEHICLE_ALIASES[vehicle] || vehicle;
}

export function getVehicleNameFromCode(code) {
  return VEHICLE_CODES[String(code || '').trim().toUpperCase()] || '';
}

export function getVehicleExportLabel(vehicle) {
  return VEHICLE_EXPORT_LABELS[vehicle]
    || VEHICLE_EXPORT_LABELS[getCanonicalVehicleName(vehicle)]
    || vehicle;
}

export function getVehicleDisplayName(vehicle) {
  return VEHICLE_DISPLAY_NAMES[vehicle]
    || VEHICLE_DISPLAY_NAMES[getCanonicalVehicleName(vehicle)]
    || getVehicleExportLabel(vehicle);
}

export function getVehicleColor(vehicle) {
  const canonical = getCanonicalVehicleName(vehicle);
  return VEHICLE_COLORS[canonical] || VEHICLE_COLORS[vehicle] || '#16a34a';
}
